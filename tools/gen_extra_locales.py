def build_locale(en: dict, loc: dict) -> dict:
    """Build a complete locale document from en-US keys + translation maps."""
    en_tr = en["translations"]
    out = {
        "meta": {
            "target_language": loc["code"],
            "target_language_display_name": loc["display"],
            "source_language": "en-US",
            "encoding": "UTF-8 (valid JSON)",
            "rtl": bool(loc["rtl"]),
        },
        "translations": {},
    }

    # settings_window: all en keys + language names
    sw = {}
    for k in en_tr["settings_window"]:
        sw[k] = loc["sw"].get(k, k)
    for k, v in loc["names"].items():
        sw[k] = v
    out["translations"]["settings_window"] = sw

    def _is_lang_key(k: str) -> bool:
        return k in LANG_KEYS or k == "Arabic"

    # overlay_display — keep compact FPS/CPU/GPU specs; translate user-facing extras
    od = {}
    for k in en_tr["overlay_display"]:
        if _is_lang_key(k):
            continue
        od[k] = loc.get("overlay", {}).get(k, k)
    out["translations"]["overlay_display"] = od

    # context_menu
    cm = {}
    for k in en_tr["context_menu"]:
        if _is_lang_key(k):
            continue
        cm[k] = loc["menu"].get(k, k)
    out["translations"]["context_menu"] = cm

    # tray
    tray = {}
    for k in en_tr["tray"]:
        if _is_lang_key(k):
            continue
        tray[k] = loc.get("tray", {}).get(k, k)
    out["translations"]["tray"] = tray

    # application_identity
    app = {}
    for k in en_tr["application_identity"]:
        if _is_lang_key(k):
            continue
        app[k] = loc.get("identity", {}).get(k, k)
    out["translations"]["application_identity"] = app

    return out


def patch_existing_lang_names(path: Path, names: dict[str, str]) -> int:
    """Insert missing language-name keys into settings_window. Returns added count."""
    data = json.loads(path.read_text(encoding="utf-8"))
    sw = data["translations"]["settings_window"]
    added = 0
    for k, v in names.items():
        if k not in sw:
            sw[k] = v
            added += 1
        elif k in ("Persian", "French", "Dutch", "German", "Italian", "Spanish",
                   "Portuguese", "Portuguese (Portugal)", "Japanese", "Korean",
                   "Russian", "Polish", "Turkish") and sw.get(k) == k and names[k] != k:
            # For zh/ar, refresh English stubs if we previously had identity
            pass
    # Always set the provided translations for the language-name keys in zh/ar
    for k, v in names.items():
        if path.name != "en-US.json":
            if k not in sw or sw[k] == k or k in names:
                if path.name in ("zh-CN.json", "ar.json"):
                    sw[k] = v
        else:
            sw.setdefault(k, v)
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return added


def write_json(path: Path, data: dict) -> None:
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    en = json.loads(EN_PATH.read_text(encoding="utf-8"))
    locales = [
        _fr(), _nl(), _de(), _it(), _es(),
        _pt_br(), _pt_pt(), _ja(), _ko(),
        _ru(), _pl(), _tr(), _fa(),
    ]

    results = []
    for loc in locales:
        doc = build_locale(en, loc)
        out_path = LOCALES_DIR / f"{loc['code']}.json"
        write_json(out_path, doc)
        sw_n = len(doc["translations"]["settings_window"])
        results.append((out_path.name, sw_n, loc["code"]))

    # Update existing locale language-name keys
    patch_existing_lang_names(LOCALES_DIR / "en-US.json", EN_LANG_NAMES)
    # Force-write all zh/ar language names
    for path, names in (
        (LOCALES_DIR / "zh-CN.json", ZH_LANG_NAMES),
        (LOCALES_DIR / "ar.json", AR_LANG_NAMES),
    ):
        data = json.loads(path.read_text(encoding="utf-8"))
        sw = data["translations"]["settings_window"]
        for k, v in names.items():
            sw[k] = v
        write_json(path, data)

    # Also ensure en-US has all language identity keys
    en2 = json.loads(EN_PATH.read_text(encoding="utf-8"))
    for k, v in EN_LANG_NAMES.items():
        en2["translations"]["settings_window"][k] = v
    write_json(EN_PATH, en2)

    print("Generated locales:")
    for name, sw_n, code in results:
        path = LOCALES_DIR / name
        data = json.loads(path.read_text(encoding="utf-8"))
        assert data["meta"]["target_language"] == code
        assert "dialogs" not in data["translations"]
        tr = data["translations"]
        missing = [k for k in LANG_KEYS if k not in tr["settings_window"]]
        if missing:
            raise SystemExit(f"{name}: missing language keys: {missing}")
        print(
            f"  {name}: settings={len(tr['settings_window'])} "
            f"overlay={len(tr['overlay_display'])} "
            f"menu={len(tr['context_menu'])} "
            f"tray={len(tr['tray'])} "
            f"app={len(tr['application_identity'])} "
            f"rtl={data['meta'].get('rtl', False)}"
        )

    # Verify updated files
    for fname in ("en-US.json", "zh-CN.json", "ar.json"):
        data = json.loads((LOCALES_DIR / fname).read_text(encoding="utf-8"))
        missing = [k for k in LANG_KEYS if k not in data["translations"]["settings_window"]]
        if missing:
            raise SystemExit(f"{fname}: missing language keys: {missing}")
        print(f"  updated {fname}: settings={len(data['translations']['settings_window'])}")

    print("OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
